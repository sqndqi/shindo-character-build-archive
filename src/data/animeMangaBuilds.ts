const REVIEW_DATE = '2026-07-29'
const UPDATE_LABEL = 'Live update pending owner retest'
const KEYS = ['1', '2', '3', '4', '5', 'T', 'V', 'B', 'N', 'C', 'Z', 'Q'] as const

type Match = Exclude<AccuracyClassification, 'Unresolved'>
type MoveInput = [
  source: string,
  ability: string,
  represented: string,
  purpose: string,
  role: string,
  accuracy: AccuracyClassification,
  flags?: 'counter' | 'mode' | 'block-break',
]

type BloodlineInput = {
  name: string
  moves: string[]
  purpose: string
  represents: string
  match: Match
  useMode?: boolean
  loreReplacement?: string
  competitiveReplacement?: string
  accessibleReplacement?: string
}

type ElementInput = {
  name: string
  moves: string[]
  purpose: string
  replacement: string
}

type VariantInput = {
  id: string
  name: string
  type: 'Two Slot' | 'Three Slot' | 'Primary'
  bloodlines: BloodlineInput[]
  elements: ElementInput[]
  cMode: string
  zMode: string
  combatArt: string
  weapon: string
  ninjaTool: string
  consumable: string
  mentor: string
  race: string
  hotbar: MoveInput[]
  combos: Combo[]
  ratings: CharacterBuild['ratings']
  strengths: string[]
  weaknesses: string[]
  usageGuide: string[]
  compromises: string[]
}

type BuildInput = {
  id: string
  name: string
  series: string
  franchise: string
  version: string
  description: string
  archetype: string[]
  combatTags: string[]
  effectsIntensity: CharacterBuild['effectsIntensity']
  characterAbilities: string[]
  variants: [BuildVariant, BuildVariant, BuildVariant]
  evidence: BuildEvidence[]
}

function hotbar(id: string, moves: MoveInput[]): HotbarSlot[] {
  if (moves.length !== KEYS.length) throw new Error(`${id} must author exactly twelve hotbar controls.`)
  return moves.map(([source, ability, characterAbility, purpose, comboRole, accuracy, flag], index) => ({
    id: `${id}-${KEYS[index]}`,
    key: KEYS[index],
    ability,
    source,
    characterAbility,
    purpose,
    comboRole,
    blockBreak: flag === 'block-break',
    counter: flag === 'counter',
    modeAbility: flag === 'mode',
    accuracy,
    usageNotes: flag === 'mode'
      ? 'Activation is authored for this variant; mode duration and resource routing still require an owner retest.'
      : 'Move spelling and source were checked against the Shindo Life community reference; confirm live timing before extending.',
  }))
}

function authoredVariant(input: VariantInput): BuildVariant {
  return {
    id: input.id,
    name: input.name,
    type: input.type,
    bloodlineSlotCount: input.bloodlines.length as 2 | 3 | 4,
    elementSlotCount: input.elements.length as 2,
    bloodlines: input.bloodlines.map((slot) => ({
      name: slot.name,
      purpose: slot.purpose,
      exactMovesUsed: slot.moves,
      useMode: slot.useMode ?? false,
      reason: `${slot.match}: ${slot.purpose}`,
      represents: slot.represents,
      replacements: {
        lore: slot.loreReplacement ? [slot.loreReplacement] : [],
        competitive: slot.competitiveReplacement ? [slot.competitiveReplacement] : [],
        accessible: slot.accessibleReplacement ? [slot.accessibleReplacement] : [],
      },
    })),
    elements: input.elements.map((element) => ({
      name: element.name,
      exactMovesUsed: element.moves,
      purpose: element.purpose,
      replacements: [element.replacement],
    })),
    cMode: input.cMode,
    zMode: input.zMode,
    combatArt: input.combatArt,
    weapon: input.weapon,
    ninjaTool: input.ninjaTool,
    consumable: input.consumable,
    mentor: input.mentor,
    race: input.race,
    hotbar: hotbar(input.id, input.hotbar),
    combos: input.combos,
    ratings: input.ratings,
    strengths: input.strengths,
    weaknesses: input.weaknesses,
    usageGuide: input.usageGuide,
    ownershipRequirements: [
      ...input.bloodlines.map((slot) => slot.name),
      ...input.elements.map((element) => element.name),
      input.combatArt,
      ...(input.weapon === 'None' ? [] : [input.weapon]),
    ],
    compromises: input.compromises,
    verificationStatus: 'Needs Retesting',
    lastVerifiedUpdate: UPDATE_LABEL,
  }
}

function evidence(character: string, primaryChoice: string, compromise: string): BuildEvidence[] {
  return [
    {
      category: 'Character',
      claim: `${character}'s named version is represented through the listed identity abilities and visual priorities.`,
      sourceTitle: `${character} community character reference`,
      sourceReference: 'Editorial reference pending',
      checkedAt: REVIEW_DATE,
      notes: 'No unconfirmed chapter or episode number is presented.',
    },
    {
      category: 'Game',
      claim: primaryChoice,
      sourceTitle: 'Shindo Life Wiki — Bloodlines and movesets',
      sourceReference: 'https://shindo-life-rell.fandom.com/wiki/Bloodline',
      checkedAt: REVIEW_DATE,
      notes: 'Move names and sources were checked individually; live behavior can change after updates.',
    },
    {
      category: 'Game',
      claim: compromise,
      sourceTitle: 'Shindo Life Wiki — game systems',
      sourceReference: 'https://shindo-life-rell.fandom.com/wiki/Shindo_Life_Wiki',
      checkedAt: REVIEW_DATE,
      notes: 'Approximation and competitive-support choices are labeled in the authored variant.',
    },
    {
      category: 'Testing',
      claim: 'All combo routes remain proposed until the owner verifies current hit timing, guard behavior, and resource costs in-game.',
      sourceTitle: 'Owner live test queue',
      sourceReference: 'Internal testing pending',
      checkedAt: REVIEW_DATE,
      notes: 'Publication is Reviewed, but verification remains Needs Retesting.',
    },
  ]
}

function combos(
  main: [string[], string],
  counter: [string[], string],
  pressure: [string[], string],
  low: [string[], string],
  mode: [string[], string],
  escape: [string[], string],
): Combo[] {
  return [
    { name: 'Main proposed testing route', sequence: main[0], explanation: main[1] },
    { name: 'Counter / reversal route', sequence: counter[0], explanation: counter[1] },
    { name: 'Guard-pressure route', sequence: pressure[0], explanation: pressure[1] },
    { name: 'Low-resource route', sequence: low[0], explanation: low[1] },
    { name: 'Mode route', sequence: mode[0], explanation: mode[1] },
    { name: 'Escape route', sequence: escape[0], explanation: escape[1] },
  ]
}

function ratings(accuracy: number, pvp: number, mobility: number, comboPotential: number, defense: number, visuals: number, aura: number, difficulty: number): CharacterBuild['ratings'] {
  return { accuracy, pvp, mobility, combos: comboPotential, defense, visuals, aura, difficulty }
}

function build(input: BuildInput): CharacterBuild {
  const primary = input.variants[2]
  return {
    id: input.id,
    characterId: `character-${input.id}`,
    versionId: `version-${input.id}`,
    buildName: `${input.name} — ${input.version}`,
    name: input.name,
    series: input.series,
    franchise: input.franchise,
    media: 'Manga / Anime',
    version: input.version,
    image: `/characters/anime/${input.id.replace('anime-', '')}.jpg`,
    thumbnail: `/characters/thumbs/${input.id.replace('anime-', '')}.webp`,
    description: input.description,
    archetype: input.archetype,
    combatTags: input.combatTags,
    customTags: ['Anime / Manga', input.franchise],
    effectsIntensity: input.effectsIntensity,
    bloodlines: primary.bloodlines.map((slot, index) => ({ id: `${input.id}-bloodline-${index + 1}`, name: slot.name, purpose: slot.purpose, useMode: slot.useMode })),
    elements: primary.elements.map((element) => element.name),
    cMode: primary.cMode,
    zMode: primary.zMode,
    combatArt: primary.combatArt,
    weapon: primary.weapon,
    ninjaTool: primary.ninjaTool,
    consumable: primary.consumable,
    mentor: primary.mentor,
    race: primary.race,
    hotbar: primary.hotbar,
    combos: primary.combos,
    strengths: primary.strengths,
    weaknesses: primary.weaknesses,
    substitutions: primary.bloodlines.flatMap((slot) => [...slot.replacements.lore, ...slot.replacements.competitive, ...slot.replacements.accessible]),
    ratings: primary.ratings,
    slotAlternatives: {
      twoSlots: input.variants[0].bloodlines.map((slot) => slot.name),
      threeSlots: input.variants[1].bloodlines.map((slot) => slot.name),
      fourSlots: primary.bloodlines.map((slot) => slot.name),
    },
    variations: {
      beginner: input.variants[0].name,
      meta: primary.name,
      lore: input.variants[1].name,
    },
    notes: 'Reviewed editorial build with exact source names; live combo timing and update compatibility still need owner testing.',
    status: 'Needs Testing',
    gameUpdate: UPDATE_LABEL,
    lastVerifiedUpdate: UPDATE_LABEL,
    verificationStatus: 'Needs Retesting',
    createdAt: REVIEW_DATE,
    updatedAt: REVIEW_DATE,
    testing: { status: 'Untested', contexts: [], tester: '', testDate: '', notes: 'Owner live test pending.' },
    changeHistory: [],
    chapterRange: 'Editorial reference pending',
    characterAbilities: input.characterAbilities,
    knownCompromises: primary.compromises ?? [],
    confidence: 'Strong Match',
    publicationStatus: 'Reviewed',
    variants: input.variants,
    evidence: input.evidence,
  }
}

